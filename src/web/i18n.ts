export const messages: Record<Locale, Record<MessageKey, string>> = { en, 'zh-CN': zh };
let locale: Locale = 'zh-CN';
export function getLocale(): Locale { return locale; }
export function setLocale(value: Locale): void { locale = value; }
export function resolveLocale(saved: string | null, languages: readonly string[]): Locale {
  if (saved === 'zh-CN' || saved === 'en') return saved;
  for (const language of languages) {
    if (/^zh(?:-|$)/i.test(language)) return 'zh-CN';
    if (/^en(?:-|$)/i.test(language)) return 'en';
  }
  return 'en';
}
export function hasMessage(key: string): key is MessageKey { return Object.hasOwn(en, key); }
export function t(key: MessageKey, params: MessageParams = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => {
    if (!Object.hasOwn(params, name)) return match;
    const value = params[name]; return typeof value === 'object' ? t(value.key, value.params) : String(value);
  });
}
export function numberLabel(value: number | bigint, options?: Intl.NumberFormatOptions): string { return new Intl.NumberFormat(locale, options).format(value); }
export class UIError extends Error {
  constructor(readonly key: MessageKey, readonly params: MessageParams = {}) { super(t(key, params)); this.name = 'UIError'; }
}
export function errorLabel(error: unknown): string {
  if (error instanceof UIError) return t(error.key, error.params);
  return t('error.decoder', { detail: error instanceof Error ? error.message : String(error) });
}
export function translateDOM(root: ParentNode = document): void {
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = node.dataset.i18n!; if (hasMessage(key)) node.textContent = t(key);
  }
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n-attrs]')) {
    for (const pair of node.dataset.i18nAttrs!.split(';')) {
      const [attribute, key] = pair.split(':'); if (attribute && key && hasMessage(key)) node.setAttribute(attribute, t(key));
    }
  }
}
