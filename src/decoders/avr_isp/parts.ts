const DEVICE_NAMES = new Map(
  DEVICES.split('\n').map((line) => {
    const separator = line.indexOf(' ');
    return [Number.parseInt(line.slice(0, separator), 16), line.slice(separator + 1)] as const;
  }),
);

export function deviceName(family: number, part: number): string | undefined {
  return DEVICE_NAMES.get(((family & 0xff) << 8) | (part & 0xff));
}
